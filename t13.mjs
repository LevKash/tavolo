import dotenv from "dotenv";
import { Client } from "pg";
dotenv.config({ path: ".env.local", quiet: true });
const c = new Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
await c.connect();
const s = await c.query("select id, table_id, status, payment_status, payment_amount, payment_order_code, opened_at from table_sessions where opened_at > now() - interval '5 hours' order by opened_at desc limit 8");
console.log("== SESSIONS");
for (const x of s.rows) console.log(x.id.slice(0,8), "|", x.status, "|pay:", x.payment_status, "|amt:", x.payment_amount, "|code:", x.payment_order_code, "|", x.opened_at.toISOString());
const o = await c.query("select id, table_session_id, status, payment_status, total, created_at from orders where created_at > now() - interval '5 hours' order by created_at desc limit 10");
console.log("\n== ORDERS");
for (const x of o.rows) console.log(x.id.slice(0,8), "|sess:", String(x.table_session_id).slice(0,8), "|", x.status, "|pay:", x.payment_status, "|EUR", x.total, "|", x.created_at.toISOString());
await c.end();
